function shapeProfile(d) {
  return {
    id: Number(d.id), code: d.distributor_code, name: d.name, contactPerson: d.contact_person || null, email: d.email || null,
    phone: d.phone_number || null, gstin: d.tax_no || null, pan: d.pan || null,
    address: {
      street1: d.street1 || null, street2: d.street2 || null, street3: d.street3 || null, street4: d.street4 || null, freeText: d.address || null,
      city: d.city || null, state: d.region || null, postalCode: d.postal_code || null, country: d.country || null,
    },
    territory: d.territory || null, effectiveTerritory: d.territory || d.city || d.region || null,
    creditLimit: money(d.credit_limit), paymentTerms: d.payment_terms || null,
    status: d.status || "active", statusReason: d.status_reason || null, statusChangedAt: iso(d.status_changed_at),
    createdAt: iso(d.createdAt), updatedAt: iso(d.updatedAt),
  };
}

// ───────────────────────── lookups ─────────────────────────
async function getLookups(db) {
  const t = tables(db);
  const run = runner(db);
  const distinct = (col) => run(`SELECT DISTINCT ${col} AS v FROM ${t.distributor} d WHERE ${col} IS NOT NULL AND ${col} <> '' ORDER BY v ASC LIMIT 500`);
  const [states, cities, territories] = await Promise.all([distinct("d.region"), distinct("d.city"), distinct(TERRITORY)]);
  return {
    statuses: STATUSES, paymentTerms: PAYMENT_TERMS,
    states: states.map((r) => r.v), cities: cities.map((r) => r.v), territories: territories.map((r) => r.v),
  };
}

// ───────────────────────── list ─────────────────────────
const SORT = {
  name: "d.name", code: "d.distributor_code", city: "d.city", state: "d.region", territory: TERRITORY, status: "d.status",
  creditLimit: "d.credit_limit", retailers: "COALESCE(rc.cnt, 0)", createdAt: "d.createdAt",
};

async function listDistributors(db, query) {
  const { page, pageSize } = q.paging(query, { defaultSize: 25, maxSize: 100 });
  const sort = q.sorting(query, SORT, { key: "name", dir: "asc" });
  const status = q.oneOf(query.status, STATUSES, "status");
  const state = q.text(query.state, "state");
  const city = q.text(query.city, "city");
  const territory = q.text(query.territory, "territory");
  const search = q.text(query.q, "q");

  const t = tables(db);
  const run = runner(db);
  const w = whereBuilder();
  if (status) w.add("d.status = :status", { status });
  if (state) w.add("d.region = :state", { state });
  if (city) w.add("d.city = :city", { city });
  if (territory) w.add(`${TERRITORY} = :territory`, { territory });
  if (search) {
    w.add(
      `(LOWER(d.name) LIKE :s ESCAPE '!' OR LOWER(d.distributor_code) LIKE :s ESCAPE '!' OR LOWER(COALESCE(d.contact_person,'')) LIKE :s ESCAPE '!'
        OR LOWER(COALESCE(d.email,'')) LIKE :s ESCAPE '!' OR COALESCE(d.phone_number,'') LIKE :s ESCAPE '!' OR LOWER(COALESCE(d.tax_no,'')) LIKE :s ESCAPE '!')`,
      { s: q.likeTerm(search) }
    );
  }
  const from = `${t.distributor} d LEFT JOIN (SELECT distributor_id, COUNT(*) AS cnt FROM ${t.customer} GROUP BY distributor_id) rc ON rc.distributor_id = d.id`;
  const [{ total }] = await run(`SELECT COUNT(*) AS total FROM ${from} ${w.sql()}`, w.params);
  const rows = await run(
    `SELECT d.id, d.distributor_code, d.name, d.contact_person, d.email, d.phone_number, d.tax_no, d.pan, d.city, d.region, d.postal_code, d.territory,
            d.credit_limit, d.payment_terms, d.status, d.createdAt, COALESCE(rc.cnt, 0) AS retailer_count
     FROM ${from} ${w.sql()} ORDER BY ${sort.column} ${sort.dir}, d.id ASC LIMIT :limit OFFSET :offset`,
    { ...w.params, limit: pageSize, offset: (page - 1) * pageSize }
  );
  return {
    items: rows.map((r) => ({
      id: Number(r.id), code: r.distributor_code, name: r.name, contactPerson: r.contact_person || null, email: r.email || null, phone: r.phone_number || null,
      gstin: r.tax_no || null, pan: r.pan || null, city: r.city || null, state: r.region || null, postalCode: r.postal_code || null,
      territory: r.territory || r.city || r.region || null, creditLimit: money(r.credit_limit), paymentTerms: r.payment_terms || null,
      status: r.status || "active", retailerCount: num(r.retailer_count), createdAt: iso(r.createdAt),
    })),
    total: num(total), page, pageSize,
  };
}

// ───────────────────────── detail ─────────────────────────
async function getDistributorDetail(db, rawId) {
  const id = q.intId(rawId, "id");
  if (!id) throw new q.QueryError("id must be a positive integer");
  const d = await db.Distributor.findOne({ where: { id }, attributes: PUBLIC_ATTRIBUTES });
  if (!d) return null;
  const t = tables(db);
  const run = runner(db);
  const p = { id, code: d.distributor_code };
  const arJoin = `${t.journal} j JOIN ${t.gl} g ON g.id = j.gl_id`;
  const arWhere = `g.gl_name = '${AR_GL_NAME}' AND j.distributor_code = :code`;
  const payWhere = `${arWhere} AND j.reference_type = 'CUSTOMER_PAYMENT'`;

  const [sales, orderAgg, ar, recentOrders, recentInvoices, recentPayments, paymentAgg, recentReturns, returnAgg, retailerAgg, retailers, pricingAgg, pricing] = await Promise.all([
    run(`SELECT COUNT(*) AS n, COALESCE(SUM(netValue),0) AS net, COALESCE(SUM(totalAmount),0) AS gross FROM ${t.invoice} WHERE distributor_id = :id AND status IN ${SALES_INVOICE_STATUSES}`, p),
    run(`SELECT COUNT(*) AS n, COALESCE(SUM(CASE WHEN status IN ${LIVE_ORDER_STATUSES} THEN 1 ELSE 0 END),0) AS live FROM ${t.order} WHERE distributor_id = :id AND status NOT IN ('DRAFT','CANCELLED')`, p),
    run(`SELECT COUNT(*) AS n, COALESCE(SUM(j.debit),0) - COALESCE(SUM(j.credit),0) AS outstanding FROM ${arJoin} WHERE ${arWhere}`, p),
    run(`SELECT o.id, o.order_number, o.orderDate, o.status, o.totalAmount, o.customerName FROM ${t.order} o WHERE o.distributor_id = :id ORDER BY o.orderDate DESC, o.id DESC LIMIT 8`, p),
    run(`SELECT i.id, i.invoice_number, i.invoiceDate, i.status, i.totalAmount, i.outstandingAmount, c.name AS customer_name FROM ${t.invoice} i LEFT JOIN ${t.customer} c ON c.id = i.customer_id WHERE i.distributor_id = :id ORDER BY i.invoiceDate DESC, i.id DESC LIMIT 8`, p),
    run(`SELECT j.id, j.reference_no, j.credit AS amount, j.transaction_date, j.narration, c.name AS customer_name FROM ${arJoin} LEFT JOIN ${t.customer} c ON c.id = j.customer_id WHERE ${payWhere} ORDER BY j.transaction_date DESC, j.id DESC LIMIT 8`, p),
    run(`SELECT COUNT(*) AS n, COALESCE(SUM(j.credit),0) AS total FROM ${arJoin} WHERE ${payWhere}`, p),
    run(`SELECT r.id, r.return_number, r.returnDate, r.status, r.reason, cn.totalAmount AS credit_amount, c.name AS customer_name FROM ${t.ret} r LEFT JOIN ${t.creditNote} cn ON cn.id = r.creditNoteId LEFT JOIN ${t.customer} c ON c.id = r.customerId WHERE r.distributor_id = :id ORDER BY r.returnDate DESC, r.id DESC LIMIT 8`, p),
    run(`SELECT COUNT(*) AS n, COALESCE(SUM(cn.totalAmount),0) AS total FROM ${t.ret} r LEFT JOIN ${t.creditNote} cn ON cn.id = r.creditNoteId WHERE r.distributor_id = :id AND r.status = 'POSTED'`, p),
    run(`SELECT COUNT(*) AS n FROM ${t.customer} WHERE distributor_id = :id`, p),
    run(`SELECT id, customer_code, name, city, region FROM ${t.customer} WHERE distributor_id = :id ORDER BY name ASC LIMIT 8`, p),
    run(`SELECT COUNT(*) AS n FROM ${t.pricing} WHERE distributor_id = :id`, p),
    run(`SELECT pm.id, pm.base_price, pm.discount_percent, pm.valid_from, pm.valid_to, pr.name AS product_name, g.name AS group_name FROM ${t.pricing} pm JOIN ${t.product} pr ON pr.id = pm.productId LEFT JOIN ${t.group} g ON g.id = pm.customer_group_id WHERE pm.distributor_id = :id ORDER BY pm.valid_from DESC, pm.id DESC LIMIT 8`, p),
  ]);

  // Outstanding = Accounts Receivable ledger balance (same definition as the Admin dashboard). null = no receivable ledger yet.
  const outstanding = num(ar[0] && ar[0].n) > 0 ? money(ar[0].outstanding) : null;
  const creditLimit = money(d.credit_limit);
  const now = new Date();

  const orders = recentOrders.map((o) => ({ id: Number(o.id), number: o.order_number, date: iso(o.orderDate), status: o.status, total: money(o.totalAmount), retailer: o.customerName || null }));
  const invoices = recentInvoices.map((i) => ({ id: Number(i.id), number: i.invoice_number, date: iso(i.invoiceDate), status: i.status, total: money(i.totalAmount), outstanding: money(i.outstandingAmount), retailer: i.customer_name || null }));
  const payments = recentPayments.map((x) => ({ id: Number(x.id), reference: x.reference_no || null, date: iso(x.transaction_date), amount: money(x.amount), retailer: x.customer_name || null, narration: x.narration || null }));
  const returns = recentReturns.map((r) => ({ id: Number(r.id), number: r.return_number, date: iso(r.returnDate), status: r.status, reason: r.reason || null, creditAmount: money(r.credit_amount), retailer: r.customer_name || null }));

  // Business activity is derived from existing documents (no audit-log table exists yet — documented), plus the last status change.
  const activity = [
    ...orders.map((o) => ({ at: o.date, type: "Order", text: `Order ${o.number || `#${o.id}`} — ${o.status}` })),
    ...invoices.map((i) => ({ at: i.date, type: "Invoice", text: `Invoice ${i.number || `#${i.id}`} — ${i.status}` })),
    ...payments.map((x) => ({ at: x.date, type: "Payment", text: `Payment received${x.reference ? ` (${x.reference})` : ""}` })),
    ...returns.map((r) => ({ at: r.date, type: "Return", text: `Return ${r.number || `#${r.id}`} — ${r.status}` })),
    ...(d.status_changed_at ? [{ at: iso(d.status_changed_at), type: "Status", text: `Status set to ${d.status}${d.status_reason ? ` — ${d.status_reason}` : ""}` }] : []),
  ].filter((a) => a.at).sort((a, b) => (a.at < b.at ? 1 : -1)).slice(0, 12);

  return {
    ...shapeProfile(d),
    summary: {
      salesInvoiced: money(sales[0].gross), salesNet: money(sales[0].net), invoiceCount: num(sales[0].n),
      orderCount: num(orderAgg[0].n), liveOrderCount: num(orderAgg[0].live),
      outstanding, creditLimit, availableCredit: creditLimit !== null && outstanding !== null ? tax.round2(creditLimit - outstanding) : null,
      paymentsReceived: money(paymentAgg[0].total), paymentCount: num(paymentAgg[0].n),
      returnCount: num(returnAgg[0].n), returnValue: money(returnAgg[0].total),
      retailerCount: num(retailerAgg[0].n), pricingCount: num(pricingAgg[0].n),
    },
    recentOrders: orders, recentInvoices: invoices, recentPayments: payments, recentReturns: returns,
    retailers: retailers.map((r) => ({ id: Number(r.id), code: r.customer_code, name: r.name, city: r.city || null, state: r.region || null })),
    pricing: pricing.map((r) => ({
      id: Number(r.id), product: r.product_name, customerGroup: r.group_name || null, basePrice: money(r.base_price), discountPercent: num(r.discount_percent),
      validFrom: iso(r.valid_from), validTo: iso(r.valid_to), active: !r.valid_to || new Date(r.valid_to) >= now,
    })),
    schemes: { supported: false }, // no Scheme model exists yet (audit: future table) — nothing is invented
    activity,
  };
}

// Retailers (Customers) that belong to this distributor — read-only, via Customer.distributor_id.
async function listDistributorRetailers(db, rawId, query) {
  const id = q.intId(rawId, "id");
  if (!id) throw new q.QueryError("id must be a positive integer");
  if (!(await db.Distributor.count({ where: { id } }))) return null;
  const { page, pageSize } = q.paging(query, { defaultSize: 10, maxSize: 100 });
  const search = q.text(query.q, "q");
  const t = tables(db);
  const run = runner(db);
  const w = whereBuilder();
  w.add("c.distributor_id = :id", { id });
  if (search) w.add("(LOWER(c.name) LIKE :s ESCAPE '!' OR LOWER(c.customer_code) LIKE :s ESCAPE '!' OR LOWER(COALESCE(c.city,'')) LIKE :s ESCAPE '!')", { s: q.likeTerm(search) });
  const [{ total }] = await run(`SELECT COUNT(*) AS total FROM ${t.customer} c ${w.sql()}`, w.params);
  const rows = await run(
    `SELECT c.id, c.customer_code, c.name, c.city, c.region, c.taxNumber, g.name AS group_name FROM ${t.customer} c LEFT JOIN ${t.group} g ON g.id = c.customer_group_id ${w.sql()} ORDER BY c.name ASC, c.id ASC LIMIT :limit OFFSET :offset`,
    { ...w.params, limit: pageSize, offset: (page - 1) * pageSize }
  );
  return {
    items: rows.map((r) => ({ id: Number(r.id), code: r.customer_code, name: r.name, city: r.city || null, state: r.region || null, gstin: r.taxNumber || null, group: r.group_name || null })),
    total: num(total), page, pageSize,
  };
}

// ───────────────────────── writes ─────────────────────────
async function assertUnique(db, { email, tax_no }, excludeId, transaction) {
  const errors = {};
  const { Op, fn, col, where } = db.Sequelize;
  const notSelf = excludeId ? { id: { [Op.ne]: excludeId } } : {};
  if (email) {
    const clash = await db.Distributor.findOne({ where: { [Op.and]: [where(fn("LOWER", col("email")), email.toLowerCase()), notSelf] }, attributes: ["id"], transaction });
    if (clash) errors.email = "Another distributor already uses this email address";
  }
  if (tax_no) {
    const clash = await db.Distributor.findOne({ where: { tax_no, ...notSelf }, attributes: ["id"], transaction });
    if (clash) errors.tax_no = "Another distributor is already registered with this GSTIN";
  }
  if (Object.keys(errors).length) throw new DistributorError(409, "DUPLICATE", Object.values(errors)[0], errors);
}

async function createDistributor(db, body, actor = {}) {
  const { values, errors } = validateInput(body, { partial: false });
  if (Object.keys(errors).length) throw failValidation(errors);
  const t = await db.sequelize.transaction();
  try {
    await assertUnique(db, values, null, t);
    // distributor_code comes from the model's beforeCreate hook (unique, system-owned). No password → no login is created.
    const created = await db.Distributor.create(
      { country: "India", ...values, status: values.status || "pending", password: null, status_changed_at: new Date(), created_by_admin_id: Number.isInteger(Number(actor && actor.adminId)) && Number(actor.adminId) > 0 ? Number(actor.adminId) : null },
      { transaction: t }
    );
    await t.commit();
    return { id: Number(created.id), code: created.distributor_code, status: created.status };
  } catch (err) {
    if (!t.finished) await t.rollback();
    if (err && err.name === "SequelizeUniqueConstraintError") throw new DistributorError(409, "DUPLICATE", "A distributor with this email or code already exists");
    throw err;
  }
}

const EDITABLE = ["name", "contact_person", "email", "phone_number", "tax_no", "pan", "street1", "street2", "street3", "street4", "address", "city", "region", "postal_code", "country", "territory", "credit_limit", "payment_terms"];

async function updateDistributor(db, rawId, body) {
  const id = q.intId(rawId, "id");
  if (!id) throw new q.QueryError("id must be a positive integer");
  const { values, errors } = validateInput(body || {}, { partial: true });
  if (Object.keys(errors).length) throw failValidation(errors);
  // id, distributor_code, password and status can never be changed through this path.
  const changes = Object.fromEntries(Object.entries(values).filter(([k]) => EDITABLE.includes(k)));
  const t = await db.sequelize.transaction();
  try {
    const d = await db.Distributor.findOne({ where: { id }, transaction: t, lock: t.LOCK.UPDATE });
    if (!d) {
      await t.rollback();
      return null;
    }
    await assertUnique(db, changes, id, t);
    await d.update(changes, { transaction: t });
    await t.commit();
    return { id, code: d.distributor_code, updated: Object.keys(changes) };
  } catch (err) {
    if (!t.finished) await t.rollback();
    if (err && err.name === "SequelizeUniqueConstraintError") throw new DistributorError(409, "DUPLICATE", "A distributor with this email already exists");
    throw err;
  }
}

async function setDistributorStatus(db, rawId, body = {}) {
  const id = q.intId(rawId, "id");
  if (!id) throw new q.QueryError("id must be a positive integer");
  const next = clean(body.status);
  if (next !== "active" && next !== "inactive") throw new DistributorError(400, "VALIDATION_FAILED", "Status must be active or inactive", { status: "Status must be active or inactive" });
  const reason = clean(body.reason) || null;
  if (reason && reason.length > 255) throw new DistributorError(400, "VALIDATION_FAILED", "Reason must be at most 255 characters", { reason: "Reason must be at most 255 characters" });

  const t = await db.sequelize.transaction();
  try {
    const d = await db.Distributor.findOne({ where: { id }, transaction: t, lock: t.LOCK.UPDATE });
    if (!d) {
      await t.rollback();
      return null;
    }
    const current = d.status || "active";
    if (current === next) throw new DistributorError(409, "NO_CHANGE", `Distributor is already ${current}`);
    if (!TRANSITIONS[current].includes(next)) throw new DistributorError(409, "INVALID_TRANSITION", `A ${current} distributor cannot be set to ${next}`);
    // Only the status columns change. Orders, invoices, payments, returns, batches, pricing and retailers are untouched.
    await d.update({ status: next, status_reason: next === "inactive" ? reason : null, status_changed_at: new Date() }, { transaction: t });
    await t.commit();
    return { id, code: d.distributor_code, previousStatus: current, status: next };
  } catch (err) {
    if (!t.finished) await t.rollback();
    throw err;
  }
}

