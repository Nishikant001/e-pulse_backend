// controllers/salescreditnote.controller.js
//
// A Sales Credit Note reduces what a customer owes — either standalone
// (e.g. a pricing correction, no physical goods movement) or generated
// automatically by a Sales Return (see salesreturn.controller.js, which
// calls createFromReturn() below in the same transaction as the stock
// reversal). Either way, this is the ONLY place SalesCreditNote/
// SalesCreditNoteLine rows are created and the ONLY place credit-note
// accounting is posted.
const db = require("../models");
const tax = require("../services/tax.service");
const accounting = require("../services/accounting.service");
const returnable = require("../services/returnableQuantity.service");
const {
  SalesCreditNote, SalesCreditNoteLine, SalesInvoiceHeader, SalesInvoiceLine, Customer,
} = db;

function badRequest(message) {
  return Object.assign(new Error(message), { statusCode: 400 });
}
function notFound(message) {
  return Object.assign(new Error(message), { statusCode: 404 });
}


async function generateCreditNoteNumber(distributor_code, transaction) {
  const last = await SalesCreditNote.findOne({
    where: { distributor_code }, order: [["createdAt", "DESC"], ["id", "DESC"]], transaction,
  });
  let next = 1;
  if (last?.credit_note_number) {
    next = (parseInt(String(last.credit_note_number).split("-").pop(), 10) || 0) + 1;
  }
  return `${distributor_code}-CN-${String(next).padStart(4, "0")}`;
}

/**
 * Build and persist credit note header + lines from a set of
 * {invoiceLineId, quantity} requests. Validates tenant ownership,
 * invoice status, and remaining creditable quantity per line. Does NOT
 * commit/rollback the transaction — the caller owns that (either
 * exports.create below, or salesreturn.controller.js when generating a
 * return-driven credit note).
 */
async function buildCreditNote({ distributorId, distributor_code, invoiceId, lines, reason, sourceReturnId = null, transaction }) {
  const invoice = await SalesInvoiceHeader.findOne({
    where: { id: invoiceId, distributor_id: distributorId },
    include: [{ model: SalesInvoiceLine, as: "lines" }],
    transaction,
  });
  if (!invoice) throw notFound("Invoice not found");
  if (invoice.status !== "POSTED") {
    throw badRequest("Credit notes can only be raised against a POSTED invoice");
  }
  if (!Array.isArray(lines) || lines.length === 0) {
    throw badRequest("At least one line is required");
  }

  const credit_note_number = await generateCreditNoteNumber(distributor_code, transaction);

  const header = await SalesCreditNote.create({
    invoiceId,
    distributor_id: distributorId,
    distributor_code,
    credit_note_number,
    customerId: invoice.customer_id,
    sourceReturnId,
    reason: reason || null,
    status: "DRAFT",
  }, { transaction });

  let netValue = 0, cgstAmount = 0, sgstAmount = 0, igstAmount = 0;

  for (const reqLine of lines) {
    const invoiceLine = invoice.lines.find((l) => l.id === reqLine.invoiceLineId);
    if (!invoiceLine) throw badRequest(`Invalid invoice line ID: ${reqLine.invoiceLineId}`);

    const quantity = reqLine.quantity;
    if (!Number.isInteger(quantity) || quantity <= 0) {
      throw badRequest("quantity must be a positive whole number");
    }

    // When this credit note is generated BY a Sales Return, the return's
    // own SalesReturnLine (created moments earlier, in the same POST
    // transaction) has already reserved this exact quantity against the
    // pool — re-checking here would count the same physical event twice
    // and reject a return that was correctly validated at its own
    // create() time. Only re-validate for standalone credit notes.
    if (!sourceReturnId) {
      const alreadyConsumed = await returnable.getSalesInvoiceLineConsumed(invoiceLine.id, transaction);
      const remaining = invoiceLine.quantity - alreadyConsumed;
      if (quantity > remaining) {
        throw badRequest(
          `Cannot credit more than the remaining creditable quantity for this line. ` +
          `Remaining: ${remaining}, requested: ${quantity}.`
        );
      }
    }

    // Proportional amount for a partial credit, using the invoice line's
    // own historical rate/tax — never re-derived from current pricing.
    const unitPrice = Number(invoiceLine.pricePerUnit);
    const proportion = quantity / invoiceLine.quantity;
    const lineTaxableValue = tax.round2(Number(invoiceLine.taxableValue) * proportion);
    const lineCgst = tax.round2(Number(invoiceLine.cgstAmount) * proportion);
    const lineSgst = tax.round2(Number(invoiceLine.sgstAmount) * proportion);
    const lineIgst = tax.round2(Number(invoiceLine.igstAmount) * proportion);
    const lineTotal = tax.round2(lineTaxableValue + lineCgst + lineSgst + lineIgst);

    await SalesCreditNoteLine.create({
      creditNoteId: header.id,
      invoiceLineId: invoiceLine.id,
      productId: invoiceLine.productId,
      batchId: reqLine.batchId || null,
      quantity,
      pricePerUnit: unitPrice,
      taxableValue: lineTaxableValue,
      cgstAmount: lineCgst,
      sgstAmount: lineSgst,
      igstAmount: lineIgst,
      lineTotal,
    }, { transaction });

    netValue += lineTaxableValue;
    cgstAmount += lineCgst;
    sgstAmount += lineSgst;
    igstAmount += lineIgst;
  }

  netValue = tax.round2(netValue);
  cgstAmount = tax.round2(cgstAmount);
  sgstAmount = tax.round2(sgstAmount);
  igstAmount = tax.round2(igstAmount);
  const totalAmount = tax.round2(netValue + cgstAmount + sgstAmount + igstAmount);

  await header.update({ netValue, cgstAmount, sgstAmount, igstAmount, totalAmount, amount: totalAmount }, { transaction });
  return header;
}

// ======================== CREATE (standalone, DRAFT) ======================== //
exports.create = async (req, res) => {
  const t = await db.sequelize.transaction();
  try {
    const distributorId = req.user.id;
    const distributor_code = req.user.distributor_code;
    const { invoiceId, lines, reason } = req.body;

    if (!invoiceId) throw badRequest("invoiceId is required");

    const header = await buildCreditNote({
      distributorId, distributor_code, invoiceId, lines, reason, transaction: t,
    });

    await t.commit();
    res.status(201).json({ message: "Credit note created (draft)", creditNote: header });
  } catch (error) {
    await t.rollback();
    console.error("Credit Note Create Error:", error.message);
    res.status(error.statusCode || 500).json({ error: error.statusCode ? error.message : "Error creating credit note" });
  }
};

exports.createFromReturn = buildCreditNote; // reused by salesreturn.controller.js

/**
 * Post the accounting for an already-built (DRAFT) credit note: reverses
 * the corresponding slice of the original invoice's revenue/tax and
 * reduces the customer's receivable. Extracted from the HTTP `post`
 * handler so salesreturn.controller.js can post the credit note's
 * accounting in the SAME transaction as the stock reversal — a posted
 * return must never leave its financial adjustment sitting in DRAFT.
 */
async function postCreditNoteAccounting(note, distributor_code, transaction) {
  if (note.status !== "DRAFT") throw badRequest(`Cannot post a credit note with status ${note.status}`);

  const receivableGL = await accounting.getGL("Accounts Receivable", distributor_code, transaction);
  const salesGL = await accounting.getGL("Sales", distributor_code, transaction);
  const transaction_date = new Date();

  const journalRows = [
    {
      distributor_code, gl_id: salesGL, reference_no: note.id, reference_type: "SALES_CREDIT_NOTE",
      debit: note.netValue, credit: 0, customer_id: note.customerId, transaction_date,
      narration: `Sales reversal — ${note.credit_note_number}`,
    },
  ];

  const totalTax = tax.round2(Number(note.cgstAmount) + Number(note.sgstAmount) + Number(note.igstAmount));
  if (totalTax > 0) {
    const gstGL = await accounting.getGL("Output GST", distributor_code, transaction);
    journalRows.push({
      distributor_code, gl_id: gstGL, reference_no: note.id, reference_type: "SALES_CREDIT_NOTE",
      debit: totalTax, credit: 0, customer_id: note.customerId, transaction_date,
      narration: `Output GST reversal — ${note.credit_note_number}`,
    });
  }

  journalRows.push({
    distributor_code, gl_id: receivableGL, reference_no: note.id, reference_type: "SALES_CREDIT_NOTE",
    debit: 0, credit: note.totalAmount, customer_id: note.customerId, transaction_date,
    narration: `Receivable reduced — ${note.credit_note_number}`,
  });

  accounting.assertBalanced(journalRows);
  for (const row of journalRows) {
    await db.JournalEntry.create(row, { transaction });
  }

  await note.update({ status: "POSTED", postedAt: new Date() }, { transaction });
  // Phase 12: keep the invoice's own outstandingAmount/status in line with the credit note just posted (same transaction).
  await require("../services/payments.service").refreshInvoiceBalance(note.invoiceId, transaction);
  return note;
}
exports.postCreditNoteAccounting = postCreditNoteAccounting;

// ======================== POST ======================== //
// DRAFT -> POSTED. Reverses the corresponding slice of the original
// invoice's revenue/tax and reduces the customer's receivable — in the
// same transaction as the status change.
exports.post = async (req, res) => {
  const t = await db.sequelize.transaction();
  try {
    const distributorId = req.user.id;
    const distributor_code = req.user.distributor_code;

    const note = await SalesCreditNote.findOne({
      where: { id: req.params.id, distributor_id: distributorId },
      transaction: t,
      lock: t.LOCK.UPDATE,
    });
    if (!note) throw notFound("Credit note not found");

    await postCreditNoteAccounting(note, distributor_code, t);

    await t.commit();
    res.json({ message: "Credit note posted", creditNote: note });
  } catch (error) {
    await t.rollback();
    console.error("Credit Note Post Error:", error.message);
    res.status(error.statusCode || 500).json({ error: error.statusCode ? error.message : "Error posting credit note" });
  }
};

exports.cancel = async (req, res) => {
  try {
    const note = await SalesCreditNote.findOne({ where: { id: req.params.id, distributor_id: req.user.id } });
    if (!note) return res.status(404).json({ error: "Credit note not found" });
    if (note.status !== "DRAFT") {
      return res.status(400).json({ error: "Only a DRAFT credit note can be cancelled directly" });
    }
    await note.update({ status: "CANCELLED" });
    res.json({ message: "Credit note cancelled", creditNote: note });
  } catch (error) {
    console.error("Credit Note Cancel Error:", error.message);
    res.status(500).json({ error: "Error cancelling credit note" });
  }
};

exports.getAll = async (req, res) => {
  try {
    const notes = await SalesCreditNote.findAll({
      where: { distributor_id: req.user.id },
      include: [
        { model: Customer, as: "customer" },
        { model: SalesCreditNoteLine, as: "lines" },
      ],
      order: [["createdAt", "DESC"]],
    });
    res.json(notes);
  } catch (error) {
    console.error("Credit Note GetAll Error:", error.message);
    res.status(500).json({ error: "Error fetching credit notes" });
  }
};

exports.getOne = async (req, res) => {
  try {
    const note = await SalesCreditNote.findOne({
      where: { id: req.params.id, distributor_id: req.user.id },
      include: [
        { model: Customer, as: "customer" },
        { model: SalesCreditNoteLine, as: "lines", include: [{ model: db.Product, as: "product" }] },
        { model: SalesInvoiceHeader, as: "invoice" },
      ],
    });
    if (!note) return res.status(404).json({ message: "Credit note not found" });
    res.json(note);
  } catch (error) {
    console.error("Credit Note GetOne Error:", error.message);
    res.status(500).json({ error: "Error fetching credit note" });
  }
};

// Only non-financial fields may be edited, and only while DRAFT.
exports.update = async (req, res) => {
  try {
    const note = await SalesCreditNote.findOne({ where: { id: req.params.id, distributor_id: req.user.id } });
    if (!note) return res.status(404).json({ message: "Credit note not found" });
    if (note.status !== "DRAFT") {
      return res.status(400).json({ error: "Only a DRAFT credit note can be edited" });
    }
    const { reason } = req.body;
    await note.update({ reason: reason ?? note.reason });
    res.json(note);
  } catch (error) {
    console.error("Credit Note Update Error:", error.message);
    res.status(500).json({ error: "Error updating credit note" });
  }
};

exports.delete = async (req, res) => {
  try {
    const note = await SalesCreditNote.findOne({ where: { id: req.params.id, distributor_id: req.user.id } });
    if (!note) return res.status(404).json({ message: "Credit note not found" });
    if (note.status !== "DRAFT") {
      return res.status(400).json({ error: "Only a DRAFT credit note can be deleted; POSTED notes are never deleted" });
    }
    await SalesCreditNoteLine.destroy({ where: { creditNoteId: note.id } });
    await note.destroy();
    res.json({ message: "Credit note deleted successfully" });
  } catch (error) {
    console.error("Credit Note Delete Error:", error.message);
    res.status(500).json({ error: "Error deleting credit note" });
  }
};
